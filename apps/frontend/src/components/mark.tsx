// The Vortex mark, inlined rather than loaded as an <img> so it inherits
// currentColor and costs no request.
//
// Three tiers exist because one geometry cannot span 256px to 16px: measured at
// real sizes, the three-stripe arms close up into a solid hexagon below roughly
// 96px. See docs/design/assets/ASSETS.md.
//
// Each tier stores ONE arm and repeats it with six exact rotate() transforms,
// so the mark is symmetric by construction rather than by a trace's luck.

type Props = { size?: number; title?: string; className?: string };

function Arm({ id, d }: { id: string; d: string }) {
  return (
    <>
      <defs>
        <path id={id} d={d} />
      </defs>
      <g fill="currentColor" fillRule="evenodd">
        {[0, 1, 2, 3, 4, 5].map((i) => (
          <use key={i} href={`#${id}`} transform={`rotate(${i * 60} 32 32)`} />
        ))}
      </g>
    </>
  );
}

