export function Mark({ size = 32, title = "Study Tracker", className }: Props) {
  const d = size >= 96 ? LARGE : size >= 32 ? MEDIUM : SMALL;
  const id = size >= 96 ? "vx-l" : size >= 32 ? "vx-m" : "vx-s";
  return (
    <svg
      viewBox="0 0 64 64"
      width={size}
      height={size}
      role="img"
      aria-label={title}
      className={className}
    >
      <title>{title}</title>
      <Arm id={id} d={d} />
    </svg>
  );
}
