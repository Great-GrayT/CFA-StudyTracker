import type { NextConfig } from "next";

// The CSP forbids every third-party origin. That is only possible because both
// variable fonts are self-hosted (see src/app/fonts), and it is what makes the
// httpOnly-cookie token strategy actually worth something: an injected script
// has nowhere to send a stolen value.
//
// `connect-src 'self'` is deliberate and load bearing. The browser never talks
// to cfa.polarislab.ir directly; every API call goes through the same-origin
// proxy at /api/proxy, which attaches the bearer token server side.
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "Referrer-Policy", value: "same-origin" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
